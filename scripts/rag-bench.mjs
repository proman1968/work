// ── воркер: тот же протокол, что в производстве ─────────────────────────────
function makeWorker() {
    const w = new Worker(new URL('../sources/modules/rag/embed-worker.js', import.meta.url));
    let seq = 0;
    const pending = new Map();
    w.on('message', ({ id, vecs, error, rss }) => {
        const p = pending.get(id);
        if (!p)
            return;
        pending.delete(id);
        error ? p.reject(new Error(error)) : p.resolve({ vecs, rss });
    });
    return {
        call: (texts, model, dtype) => new Promise((resolve, reject) => {
            const id = ++seq;
            pending.set(id, { resolve, reject });
            w.postMessage({ id, texts, model, dtype });
        }),
        stop: () => w.terminate().catch(() => {}),
    };
}

const dot = (a, b) => { let s = 0; for (let i = 0; i < a.length; i++) s += a[i] * b[i]; return s; };

async function bench(mode) {
    const w = makeWorker();
    try {
        const docTexts = DOCS.map(([title, text]) => docInput(title, text, mode.model));
        const queryTexts = QUERIES.map(([q]) => queryInput(q, mode.model));
        // загрузка модели (первый вызов — скачивание при отсутствии в кэше)
        const t0 = Date.now();
        const first = await w.call(docTexts.slice(0, 1), mode.model, mode.dtype);
        const loadMs = Date.now() - t0;
        const dims = first.vecs[0].length;
        // документы пакетами по 8 (как CONFIG.batch)
        const batches = [];
        for (let i = 1; i < docTexts.length; i += 8)
            batches.push(docTexts.slice(i, i + 8));
        const t1 = Date.now();
        const rest = [];
        let rss = first.rss;
        for (const b of batches) {
            const r = await w.call(b, mode.model, mode.dtype);
            rest.push(...r.vecs);
            rss = Math.max(rss, r.rss);
        }
        const docMs = (Date.now() - t1) / batches.length;
        const docVecs = [first.vecs[0], ...rest];
        // запросы одним пакетом
        const tq = Date.now();
        const qr = await w.call(queryTexts, mode.model, mode.dtype);
        const queryMs = Date.now() - tq;
        rss = Math.max(rss, qr.rss);
        // качество: косинус, ранжирование
        let hit1 = 0, hit3 = 0, mrr = 0;
        for (let qi = 0; qi < QUERIES.length; qi++) {
            const want = QUERIES[qi][1];
            const sims = docVecs.map((v, di) => [dot(v, qr.vecs[qi]), di]).sort((a, b) => b[0] - a[0]);
            const rank = sims.findIndex(([, di]) => di === want) + 1;
            if (rank === 1) hit1++;
            if (rank <= 3) hit3++;
            if (rank > 0) mrr += 1 / rank;
        }
        const n = QUERIES.length;
        return {
            ...mode, dims, loadMs,
            msPerBatch: Math.round(docMs),
            queryMs,
            rss: Math.round(rss / 1048576),
            hit1: (hit1 / n * 100).toFixed(0),
            hit3: (hit3 / n * 100).toFixed(0),
            mrr: (mrr / n).toFixed(3),
        };
    }
    finally {
        await w.stop();
    }
}

